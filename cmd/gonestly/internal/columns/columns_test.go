func TestGenerate(t *testing.T) {
	dir := t.TempDir()
	files := map[string]string{
		"model.go": `package shop

import (
	"database/sql"
	"time"

	"github.com/google/uuid"
)

type Base struct {
	ID        int64     ` + "`db:\"id\"`" + `
	CreatedAt time.Time ` + "`db:\"created_at,default\"`" + `
}

type Product struct {
	Base
	Name     string         ` + "`db:\"name\"`" + `
	Note     sql.NullString ` + "`db:\"note\"`" + `
	Ref      uuid.UUID
	Price    *int64         ` + "`db:\"price_cents\"`" + `
	Tags     []string       ` + "`db:\"tags\"`" + `
	Internal string         ` + "`db:\"-\"`" + `
	hidden   string
}

type notAModel struct{ X int }

type Settings struct{ Theme string }
`,
		"model_test.go": "package shop\n\ntype TestOnly struct{ A int `db:\"a\"` }\n",
	}
	for name, content := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	models, err := Generate(dir)
	if err != nil || strings.Join(models, ",") != "Product" {
		t.Fatalf("models = %v, err = %v", models, err)
	}
	got, _ := os.ReadFile(filepath.Join(dir, FileName))
	want := `// Code generated by gonestly generate columns; DO NOT EDIT.

package shop

import (
	"database/sql"
	"time"

	"github.com/google/uuid"
	gonestlysql "github.com/yaboylino/gonestly/sql"
)

// ProductColumns are the columns of Product, for typed queries.
var ProductColumns = struct {
	ID        gonestlysql.Column[int64]
	CreatedAt gonestlysql.Column[time.Time]
	Name      gonestlysql.Column[string]
	Note      gonestlysql.Column[sql.NullString]
	Ref       gonestlysql.Column[uuid.UUID]
	Price     gonestlysql.Column[*int64]
	Tags      gonestlysql.Column[[]string]
}{
	ID:        gonestlysql.Col[int64]("id"),
	CreatedAt: gonestlysql.Col[time.Time]("created_at"),
	Name:      gonestlysql.Col[string]("name"),
	Note:      gonestlysql.Col[sql.NullString]("note"),
	Ref:       gonestlysql.Col[uuid.UUID]("ref"),
	Price:     gonestlysql.Col[*int64]("price_cents"),
	Tags:      gonestlysql.Col[[]string]("tags"),
}
`
	if string(got) != want {
		t.Errorf("got:\n%s\nwant:\n%s", got, want)
	}

	if err := os.WriteFile(filepath.Join(dir, "model.go"), []byte("package shop\n\ntype Settings struct{ Theme string }\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if models, err := Generate(dir); err != nil || len(models) != 0 {
		t.Errorf("models = %v, err = %v", models, err)
	}
	if _, err := os.Stat(filepath.Join(dir, FileName)); !os.IsNotExist(err) {
		t.Error("the generated file was not removed when no models remain")
	}
}

func TestGenerateErrors(t *testing.T) {
	if _, err := Generate(t.TempDir()); err == nil || !strings.Contains(err.Error(), "has no Go files") {
		t.Errorf("err = %v", err)
	}
	dir := t.TempDir()
	_ = os.WriteFile(filepath.Join(dir, "a.go"), []byte("package a\n"), 0o600)
	_ = os.WriteFile(filepath.Join(dir, "b.go"), []byte("package b\n"), 0o600)
	if _, err := Generate(dir); err == nil || !strings.Contains(err.Error(), "more than one package") {
		t.Errorf("err = %v", err)
	}
	dir = t.TempDir()
	_ = os.WriteFile(filepath.Join(dir, "a.go"), []byte("package a\n\ntype M struct{ F missing.Type `db:\"f\"` }\n"), 0o600)
	if _, err := Generate(dir); err == nil || !strings.Contains(err.Error(), "the package missing is not imported") {
		t.Errorf("err = %v", err)
	}
}

